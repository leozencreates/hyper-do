export const DICTS: Record<Lang, Dict> = { tr, en, ru }

export type Key = Exclude<keyof Dict, 'fun' | 'fun_overdue'>

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

/** Rastgele eğlenceli bildirim başlığı. Aynı başlığın art arda gelmesini engeller. */
let lastFunIndex = -1
export function funTitle(lang: Lang, taskTitle: string, overdue: boolean): string {
  const pool = overdue ? DICTS[lang].fun_overdue : DICTS[lang].fun
  let i = Math.floor(Math.random() * pool.length)
  if (pool.length > 1 && i === lastFunIndex) i = (i + 1) % pool.length
  lastFunIndex = i
  return pool[i].replace('{title}', taskTitle)
}

export function detectLang(): Lang {
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'en'
  if (nav.startsWith('ru')) return 'ru'
  if (nav.startsWith('tr')) return 'tr'
  return 'en'
}
